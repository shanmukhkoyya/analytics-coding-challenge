-- 4. BUSINESS QUESTIONS
-- ============================================================

-- Q1. List all customers who have placed at least one order.
SELECT DISTINCT
    c.customer_id,
    c.name,
    c.city
FROM Customers c
INNER JOIN Orders o
    ON c.customer_id = o.customer_id;

-- Q2. Find the total amount spent by each customer.
SELECT
    customer_id,
    SUM(amount) AS total_amount
FROM Orders
GROUP BY customer_id
ORDER BY total_amount DESC;

-- Q3. Display the top 3 customers based on total spending.
SELECT
    customer_id,
    SUM(amount) AS total_amount
FROM Orders
GROUP BY customer_id
ORDER BY total_amount DESC
LIMIT 3;

-- Q4. Retrieve orders placed in the last 7 days
--     from the latest order date in the dataset.
SELECT *
FROM Orders
WHERE order_date >= DATE_SUB(
    (SELECT MAX(order_date) FROM Orders),
    INTERVAL 7 DAY
)
ORDER BY order_date DESC;

-- Q5. Show customers who have never placed an order.
SELECT
    c.customer_id,
    c.name,
    c.city
FROM Customers c
LEFT JOIN Orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- Q6. Find the restaurant that received the highest number of orders.
SELECT
    restaurant,
    COUNT(order_id) AS total_orders
FROM Orders
GROUP BY restaurant
ORDER BY total_orders DESC
LIMIT 1;

-- Q7. List Bengaluru customers who spent more than ₹1,000.
SELECT
    c.customer_id,
    c.name,
    c.city,
    SUM(o.amount) AS total_spent
FROM Customers c
INNER JOIN Orders o
    ON c.customer_id = o.customer_id
WHERE c.city = 'Bengaluru'
GROUP BY
    c.customer_id,
    c.name,
    c.city
HAVING SUM(o.amount) > 1000
ORDER BY total_spent DESC;

-- Q8. Show the total number of orders placed per city.
SELECT
    c.city,
    COUNT(o.order_id) AS orders_count
FROM Customers c
INNER JOIN Orders o
    ON c.customer_id = o.customer_id
GROUP BY c.city
ORDER BY orders_count DESC;

-- Q9. Find the average order amount for each restaurant.
SELECT
    restaurant,
    ROUND(AVG(amount), 2) AS average_order_amount
FROM Orders
GROUP BY restaurant
ORDER BY average_order_amount DESC;

-- Q10. Identify customers who placed more than 5 orders.
SELECT
    c.customer_id,
    c.name,
    c.city,
    COUNT(o.order_id) AS order_count
FROM Customers c
INNER JOIN Orders o
    ON c.customer_id = o.customer_id
GROUP BY
    c.customer_id,
    c.name,
    c.city
HAVING COUNT(o.order_id) > 5;

-- ============================================================
-- 5. INTERVIEW PRACTICE QUESTIONS
-- ============================================================

-- A. Find the total revenue generated by the platform.
SELECT ROUND(SUM(amount), 2) AS total_revenue
FROM Orders;

-- B. Find the average order value across all orders.
SELECT ROUND(AVG(amount), 2) AS average_order_value
FROM Orders;

-- C. Find the number of unique customers who placed orders.
SELECT COUNT(DISTINCT customer_id) AS unique_ordering_customers
FROM Orders;

-- D. Find each customer's number of orders and total spending.
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS order_count,
    ROUND(SUM(o.amount), 2) AS total_spent
FROM Customers c
INNER JOIN Orders o
    ON c.customer_id = o.customer_id
GROUP BY
    c.customer_id,
    c.name
ORDER BY total_spent DESC;

-- E. Find the highest-value order.
SELECT *
FROM Orders
ORDER BY amount DESC
LIMIT 1;

